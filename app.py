from flask import Flask, render_template, request, redirect, url_for, session
import sqlite3
import threading
from google.colab import output

app = Flask(__name__)
app.secret_key = 'clave_secreta_para_sesiones'

# Inicializar la base de datos SQLite
def init_db():
    conn = sqlite3.connect('gastos.db')
    cursor = conn.cursor()
    cursor.execute('''
        CREATE TABLE IF NOT EXISTS gastos (
            id INTEGER PRIMARY KEY AUTOINCREMENT,
            fecha TEXT NOT NULL,
            descripcion TEXT NOT NULL,
            monto REAL NOT NULL
        )
    ''')
    conn.commit()
    conn.close()

@app.route('/')
def home():
    if 'admin' in session:
        return redirect(url_for('index'))
    return redirect(url_for('login'))

@app.route('/login', methods=['GET', 'POST'])
def login():
    error = None
    if request.method == 'POST':
        # Credenciales solicitadas en la tarea
        if request.form['username'] == 'admin' and request.form['password'] == '123':
            session['admin'] = True
            return redirect(url_for('index'))
        else:
            error = 'Credenciales incorrectas. Intenta de nuevo.'
    return render_template('login.html', error=error)

@app.route('/logout')
def logout():
    session.pop('admin', None)
    return redirect(url_for('login'))

@app.route('/index', methods=['GET', 'POST'])
def index():
    if 'admin' not in session:
        return redirect(url_for('login'))

    if request.method == 'POST':
        fecha = request.form['fecha']
        descripcion = request.form['descripcion']
        monto = request.form['monto']

        conn = sqlite3.connect('gastos.db')
        cursor = conn.cursor()
        cursor.execute('INSERT INTO gastos (fecha, descripcion, monto) VALUES (?, ?, ?)',
                       (fecha, descripcion, monto))
        conn.commit()
        conn.close()
        return redirect(url_for('index'))

    return render_template('index.html')

@app.route('/reporte')
def reporte():
    if 'admin' not in session:
        return redirect(url_for('login'))

    conn = sqlite3.connect('gastos.db')
    cursor = conn.cursor()
    cursor.execute('SELECT fecha, descripcion, monto FROM gastos ORDER BY fecha DESC')
    gastos = cursor.fetchall()
    conn.close()

    return render_template('reporte.html', gastos=gastos)

